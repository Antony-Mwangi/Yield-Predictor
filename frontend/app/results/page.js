  secondaryBtn: { flex: 1, display: "flex", alignItems: "center", justifyContent: "center", gap: 8, backgroundColor: "#F1F5F9", color: "#475569", padding: 14, borderRadius: 12, border: "none", fontWeight: 600, cursor: "pointer" },
