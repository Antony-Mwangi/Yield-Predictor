
"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { 
  FileText, 
  RefreshCw, 
  LayoutDashboard, 
  CheckCircle2, 
  TrendingUp,
  Sprout,
  ArrowDownToLine
} from "lucide-react";

export default function ResultsPage() {
  const [data, setData] = useState(null);
  const router = useRouter();

  useEffect(() => {
    const stored = localStorage.getItem("result");
    if (stored) setData(JSON.parse(stored));
  }, []);

  
  const downloadWord = () => {
    if (!data) return;

    const date = new Date().toLocaleDateString();
    
    
    const header = `
      <html xmlns:o='urn:schemas-microsoft-com:office:office' 
            xmlns:w='urn:schemas-microsoft-com:office:word' 
            xmlns='http://www.w3.org/TR/REC-html40'>
      <head><meta charset='utf-8'><title>Yield Report</title>
      <style>
        body { font-family: 'Segoe UI', Arial, sans-serif; line-height: 1.6; color: #333; }
        .title { color: #166534; font-size: 28pt; font-weight: bold; margin-bottom: 0; }
        .date { color: #666; font-size: 10pt; margin-bottom: 30px; }
        .yield-card { background: #f0fdf4; border: 2px solid #16a34a; padding: 20px; text-align: center; border-radius: 10px; }
        .yield-val { font-size: 36pt; color: #166534; font-weight: 800; }
        .section-h { font-size: 16pt; color: #111; border-bottom: 1px solid #eee; padding-bottom: 5px; margin-top: 30px; }
        .rec-item { margin-bottom: 10px; color: #444; }
      </style>
      </head>
      <body>
        <h1 class="title">Maize Yield Analysis Report</h1>
        <p class="date">Report Generated: ${date}</p>
        
        <div class="yield-card">
          <p style="margin:0; text-transform: uppercase; font-size: 10pt; font-weight: bold; color: #15803d;">Projected Yield</p>
          <div class="yield-val">${data.yield_prediction} T/ha</div>
        </div>

        <h2 class="section-h">Agronomic Overview</h2>
        <p>Based on your specific input metrics for Rainfall, Temperature, and Soil NPK composition, our AI model has projected a yield that reflects the current health of your soil and environmental conditions. This forecast is designed to help you plan logistics and storage effectively.</p>

        <h2 class="section-h">AI Recommendations</h2>
        <ul>
          ${data.recommendations.map(rec => `<li class="rec-item">${rec}</li>`).join('')}
        </ul>

        <p style="margin-top: 50px; font-size: 9pt; color: #999; text-align: center;">
          Generated by YieldPredictor AI. This is a computer-generated forecast.
        </p>
      </body>
      </html>
    `;

    const blob = new Blob(['\ufeff', header], {
      type: 'application/msword'
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Yield_Report_${date.replace(/\//g, '-')}.doc`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  if (!data) return <div style={styles.loader}>Analyzing...</div>;

  return (
    <div style={styles.pageWrapper}>
      <nav style={styles.topNav}>
        <div style={styles.brand}>
          <Sprout color="#16a34a" size={24} />
          <span style={styles.brandName}>YIELD<span style={{fontWeight:300}}>ANALYSIS</span></span>
        </div>
        <button onClick={downloadWord} style={styles.wordBtn}>
          <ArrowDownToLine size={18} /> Download Report (.doc)
        </button>
      </nav>

      <div style={styles.container}>
        <div style={styles.header}>
          <h1 style={styles.mainTitle}>Prediction Result</h1>
          {/* <div style={styles.statusBadge}>
            <CheckCircle2 size={16} /> Verified by AI
          </div> */}
        </div>

        <div style={styles.heroGrid}>
          <div style={styles.yieldCard}>
            <TrendingUp size={30} style={{ marginBottom: 12, opacity: 0.9 }} />
            <p style={styles.cardLabel}>Predicted Harvest</p>
            <div style={styles.yieldDisplay}>
              {data.yield_prediction} <span style={styles.unit}>T/ha</span>
            </div>
          </div>

          <div style={styles.overviewCard}>
            <h3 style={styles.cardTitle}>Executive Summary</h3>
            <p style={styles.overviewText}>
              Your farm profile indicates an optimized environment for maize growth. 
              The nutrient balance combined with local climate data suggests a robust season.
            </p>
          </div>
        </div>

        <section>
          <h3 style={styles.sectionTitle}>Required Interventions</h3>
          <div style={styles.listContainer}>
            {data.recommendations.map((rec, i) => (
              <div key={i} style={styles.listCard}>
                <div style={styles.listNumber}>{i + 1}</div>
                <p style={styles.listText}>{rec}</p>
              </div>
            ))}
          </div>
        </section>

        <footer style={styles.footer}>
          <button style={styles.secondaryBtn} onClick={() => router.push("/predict")}>
            <RefreshCw size={18} /> Run New Analysis
          </button>
          <button style={styles.primaryBtn} onClick={() => router.push("/dashboard")}>
            <LayoutDashboard size={18} /> Save to Dashboard
          </button>
        </footer>
      </div>
    </div>
  );
}

