  yieldCard: { backgroundColor: "#166534", color: "white", padding: 32, borderRadius: 20 },
  cardLabel: { margin: 0, textTransform: "uppercase", fontSize: "0.75rem", fontWeight: 700, letterSpacing: "1px", opacity: 0.8 },
  yieldDisplay: { fontSize: "3.5rem", fontWeight: 900 },
